const fs = require('node:fs')
const vm = require('node:vm')
const path = require('node:path')
const assert = require('node:assert/strict')
const source = fs.readFileSync(path.join(__dirname, '../desktop-plugins/token-optimizer-bar/plugin.js'), 'utf8')
const start = source.indexOf('function mayCompress(')
assert.notEqual(start, -1, 'compaction guard must exist')
const end = source.indexOf('\nfunction Bar(', start)
const sandbox = vm.createContext({})
vm.runInContext(source.slice(start, end), sandbox)
assert.equal(sandbox.mayCompress('s1', 's1', false), true)
assert.equal(sandbox.mayCompress('s1', 's2', false), false)
assert.equal(sandbox.mayCompress('s1', 's1', true), false)
assert.equal(sandbox.mayCompress('', '', false), false)
console.log('compaction target guards passed')
