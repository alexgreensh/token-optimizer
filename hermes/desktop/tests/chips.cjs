const fs = require('node:fs')
const vm = require('node:vm')
const path = require('node:path')
const assert = require('node:assert/strict')
const source = fs.readFileSync(path.join(__dirname, '../desktop-plugins/token-optimizer-bar/plugin.js'), 'utf8')
const start = source.indexOf('function Metric(')
const end = source.indexOf('\nfunction cacheClock(', start)
const jsx = (type, props) => ({ type, props })
const box = vm.createContext({ jsx, jsxs: jsx, Popover: 'Popover', PopoverTrigger: 'PopoverTrigger', PopoverContent: 'PopoverContent', Ring: 'Ring', accent: 'accent', muted: 'muted' })
vm.runInContext(source.slice(start, end), box)
const chip = box.Metric({ value: '85', text: 'qualità', grade: 'A', title: 'Punteggio qualità', children: 'Spiegazione qualità' })
assert.equal(chip.type, 'Popover', 'metric should open a popover')
const [trigger, content] = chip.props.children
assert.equal(trigger.type, 'PopoverTrigger')
assert.equal(trigger.props.children.type, 'button', 'metric must be keyboard accessible')
assert.equal(content.type, 'PopoverContent')
assert.equal(content.props.side, 'top')
assert.equal(content.props.children, 'Spiegazione qualità')
console.log('accessible metric popover passed')
