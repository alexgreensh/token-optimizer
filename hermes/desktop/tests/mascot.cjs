const fs = require('node:fs')
const vm = require('node:vm')
const path = require('node:path')
const assert = require('node:assert/strict')
const source = fs.readFileSync(path.join(__dirname, '../desktop-plugins/token-optimizer-bar/plugin.js'), 'utf8')
const block = source.slice(source.indexOf('function mascotFrame('), source.indexOf('\nfunction Mascot('))
assert.ok(block.startsWith('function mascotFrame('), 'mascot state helper must exist')
const sandbox = vm.createContext({})
vm.runInContext(block, sandbox)
assert.equal(sandbox.mascotFrame(0, false), 0)
assert.equal(sandbox.mascotFrame(9, false), 0)
assert.equal(sandbox.mascotFrame(1, true), 1)
assert.equal(sandbox.mascotFrame(9, true), 1)
console.log('mascot idle and busy state tests passed')
