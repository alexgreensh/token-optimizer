#!/usr/bin/env python3
"""Token Optimizer Windows launcher for Codex hooks.

Codex spawns ``command`` hooks through the session shell on native Windows
(PowerShell, ``-NoProfile -Command``) and falls back to ``%COMSPEC% /C``
(cmd.exe) when it has none, so the generated command is written to parse the
same in both (issue #278). cmd.exe parses a /C command line ONCE, before
anything on it runs:
``%VAR%`` expands to the pre-line value and ``setlocal
EnableDelayedExpansion`` only takes effect from the NEXT line, so no cmd
expansion form can carry a resolved marketplace version into the runner
path on the same line (issue #180). The pre-launcher fix embedded the
resolver as a base64 ``python -c`` exec-bootstrap,
which trips generic-loader antivirus signatures (issue #183): the match is
on the literal encoded-exec string, not on behavior, and a detection on an
install script surfaces as malware, not a warning.

This file is the replacement: a stable, readable .py that codex_install.py
copies NEXT TO the versioned install dirs (``.../token-optimizer/
windows-launcher.py``, a path that survives the marketplace swapping
``.../token-optimizer/<X.Y.Z>/`` on upgrade) and that baked hook commands
invoke by quoted path. Paths and arguments live as plainly quoted argv --
no encoded-exec string appears anywhere, and the cmd.exe single-parse
problem stays solved because nothing needs expanding.

Invocation contract (generated by codex_install._windows_launcher_command):

    python.exe "<parent>\\windows-launcher.py" --baked-root "<root>"
        [--env KEY=VALUE ...] -- <script> [args...] [MARKER]

* ``--baked-root`` is the install dir the command was generated from. It is
  the fail-open fallback only: the launcher rescans its sibling version
  dirs on every run and runs the NEWEST semver install, so hooks keep
  working after a marketplace upgrade prunes the baked one.
* ``--env KEY=VALUE`` applies per-hook environment (e.g.
  TOKEN_OPTIMIZER_NO_UPDATED_TOOL_OUTPUT=1) before dispatch.
  ``--env TOKEN_OPTIMIZER_HOOK_SILENT=1`` is not forwarded: it sends the
  hook's stdout/stderr to the null device, in place of a shell ``>NUL``.
* Everything after ``--`` is forwarded verbatim: ``sys.argv`` for the
  runner becomes ``[run.py, script, *args]`` and stdin passes through
  untouched. A trailing token equal to the generated-command ownership
  marker (token-optimizer/scripts/windows-launcher) is stripped, matching
  the old bootstrap, which dropped it when it replaced sys.argv.

Audit: the file IS the audit -- read it. For hooks.json entries baked by
the retired base64 launcher, ``codex_install.py --decode-launcher
"<command>"`` still decodes them.
"""

from __future__ import annotations

import os
import re
import runpy
import sys
from pathlib import Path

# Trailing ownership marker baked into every generated Windows launcher
# command (see codex_install._LAUNCHER_MARKER). It identifies the command
# to install/uninstall/doctor ownership checks and is never forwarded to
# the runner.
_LAUNCHER_MARKER = "token-optimizer/scripts/windows-launcher"

_SEMVER_DIR_RE = re.compile(r"\d+\.\d+\.\d+")

_USAGE = (
    "usage: windows-launcher.py --baked-root DIR [--env KEY=VALUE ...] "
    "-- SCRIPT [ARGS...]"
)


def _parse(argv: list[str]) -> tuple[str, list[str], str, list[str]]:
    """Split generated launcher argv into (baked_root, env, script, args).

    Manual parse, not argparse: hook arguments legitimately start with
    ``--`` (e.g. ``--quiet``), which argparse would misread as its own
    options. Everything after the ``--`` separator is positional.
    """
    baked_root = None
    env: list[str] = []
    i = 0
    while i < len(argv):
        token = argv[i]
        if token == "--":
            i += 1
            break
        if token in ("--baked-root", "--env") and i + 1 < len(argv):
            value = argv[i + 1]
            if token == "--baked-root":
                baked_root = value
            else:
                env.append(value)
            i += 2
            continue
        break  # unrecognized token: stop option parsing, rest is positional
    rest = argv[i:]
    if rest and rest[-1] == _LAUNCHER_MARKER:
        rest = rest[:-1]
    if not baked_root or not rest:
        raise SystemExit(_USAGE)
    return baked_root, env, rest[0], rest[1:]


_SILENT_ENV = "TOKEN_OPTIMIZER_HOOK_SILENT"


def _silence_output() -> None:
    """Point fds 1 and 2 (and the Python streams) at the null device."""
    try:
        sys.stdout.flush()
        sys.stderr.flush()
    except (OSError, ValueError):
        pass
    try:
        null = os.open(os.devnull, os.O_WRONLY)
        os.dup2(null, 1)
        os.dup2(null, 2)
        os.close(null)
    except OSError:
        pass


def main(argv: list[str] | None = None) -> None:
    baked_root, env_pairs, script, args = _parse(
        sys.argv[1:] if argv is None else argv
    )
    root = Path(baked_root)
    baked = root
    # Resolve the newest semver sibling of the install parent; on any
    # listing failure keep the baked install (fail-open, same contract the
    # retired base64 bootstrap documented).
    #
    # Windows-only launcher, so os.access(run.py, R_OK) is unusable: it maps
    # to the read-only file attribute, not the ACL, and returns True for a
    # run.py an ACL forbids reading -- runpy would then die with
    # PermissionError instead of falling back. And a bare .is_file() on a
    # candidate whose hooks/ dir can't be traversed RAISES PermissionError,
    # which on 3.12 escapes the comprehension and aborts the whole scan
    # (caught below), selecting the wrong runtime. So probe each candidate by
    # actually opening its run.py, newest-first, and take the first that
    # opens with real content: an unreadable, missing, or incomplete
    # candidate is skipped (not fatal), and a genuine ACL denial is honored.
    try:
        candidates = sorted(
            (p for p in root.parent.iterdir()
             if _SEMVER_DIR_RE.fullmatch(p.name)),
            key=lambda p: tuple(map(int, p.name.split("."))),
            reverse=True,
        )
        for candidate in candidates:
            run_py = candidate / "hooks" / "run.py"
            try:
                with open(run_py, "rb") as fh:
                    if not fh.read(1):
                        continue  # zero-byte/truncated: would run nothing rc 0
            except OSError:
                continue  # missing, incomplete upgrade, or ACL-denied
            root = candidate
            break
    except OSError:
        pass
    # The baked-install fallback is silent by design; the only observable
    # channel is a TOKEN_OPTIMIZER_DEBUG-gated line appended next to the
    # version dirs. A healthy semver resolve is not a fallback and never
    # logs.
    if root == baked and os.environ.get("TOKEN_OPTIMIZER_DEBUG"):
        try:
            with (root.parent / "token-optimizer-codex-resolver.log").open(
                "a", encoding="utf-8"
            ) as log:
                log.write(str(root) + "\n")
        except OSError:
            pass
    os.environ["TOKEN_OPTIMIZER_RUNTIME"] = "codex"
    os.environ["TOKEN_OPTIMIZER_RUNTIME_ROOT"] = str(root)
    # Per-hook "no output" request: replaces the ">NUL 2>&1" redirect, which
    # PowerShell and cmd.exe do not spell the same way (issue #278). Carried
    # as an --env pair so a launcher older than this one still parses the
    # command (it just stays noisy). Consumed here, never set in the runner's
    # environment.
    silent = False
    for pair in env_pairs:
        key, sep, value = pair.partition("=")
        if key == _SILENT_ENV:
            silent = silent or value == "1"
            continue
        if sep and key:  # skip malformed pairs rather than breaking the hook
            os.environ[key] = value
    if silent:
        _silence_output()
    runner = root / "hooks" / "run.py"
    sys.argv = [str(runner), script, *args]
    sys.path.insert(0, str(runner.parent))
    runpy.run_path(str(runner), run_name="__main__")


if __name__ == "__main__":
    main()
