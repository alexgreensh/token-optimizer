#!/usr/bin/env python3
"""Regenerate skills/token-optimizer/scripts/shipped_codex_hook_templates.json.

Codex hook commands are generated by code (codex_install._managed_hooks), with
the install root, its parent and, on Windows, the interpreter path baked in.
To prove a Codex hook is ours by exact bytes, this script runs EVERY committed
version of codex_install.py (its whole scripts dir at that commit) with
placeholder paths, on the POSIX and the win32 code path, every optional hook
enabled, and stores each resulting entry, (event, matcher, hook type,
command), as a frozen template. At runtime codex_hook_provenance substitutes
this machine's real paths and each shipped version number back into the
command and compares the whole entry byte for byte, so our command copied
into another event or matcher is not ours.

    python3 scripts/gen_shipped_codex_hook_templates.py [--ref HEAD]

Only ever adds templates/versions, never drops them.
"""
from __future__ import annotations

import argparse
import ast
import json
import shutil
import subprocess
import sys
import tarfile
import io
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCRIPTS = "skills/token-optimizer/scripts"
OUT = REPO / SCRIPTS / "shipped_codex_hook_templates.json"
WORK = REPO / ".scratch-review" / "codex-harvest"

# Placeholders. Variant "plain" uses only characters shlex.quote and
# list2cmdline leave bare, like a real path without spaces. The "S" variants put
# a space in the install paths (P) and/or the interpreter path (Y), so the
# generator quotes them exactly as it quotes a real spaced path
# (C:\\Users\\Dana Q\\...). Runtime picks the variant matching the real paths.
def _sentinels(sep, drive, path_space, py_space):
    a = "TOSENT P" if path_space else "TOSENTP"
    d = "TOSENT D" if path_space else "TOSENTD"
    y = "TOSENT PY" if py_space else "TOSENTPY"
    parent = drive + sep + a + sep + "token-optimizer"
    return {"parent": parent, "root": parent + sep + "9.99.999", "dev": drive + sep + d + sep + "devroot",
            "python": drive + sep + y + sep + ("python.exe" if sep == "\\" else "bin" + sep + "python3")}


VARIANTS = {f"{'S' if ps else 'P'}{'S' if ys else 'P'}": (ps, ys) for ps in (False, True) for ys in (False, True)}
POSIX = {k: _sentinels("/", "", *v) for k, v in VARIANTS.items()}
WINDOWS = {k: _sentinels("\\", "C:", *v) for k, v in VARIANTS.items()}

HARVEST = r'''
import inspect, json, sys
from pathlib import PurePosixPath, PureWindowsPath
plat, sent = sys.argv[2], json.loads(sys.argv[3])
sys.path.insert(0, sys.argv[1])
import codex_install as ci  # import natively, then flip the platform (as the tests do)
sys.platform = plat
sys.executable = sent["python"]
P = PureWindowsPath if plat == "win32" else PurePosixPath
out = []
for kind in ("root", "dev"):
    ci._repo_root = lambda r=P(sent[kind]): r
    fn = ci._managed_hooks
    kw = {n: True for n, p in inspect.signature(fn).parameters.items()
          if p.kind == p.KEYWORD_ONLY or isinstance(p.default, bool)}
    hooks = fn(**kw)
    for event, groups in hooks.items():
        for g in groups:
            for h in g.get("hooks", []):
                if isinstance(h.get("command"), str):
                    out.append([event, g.get("matcher", ""), h.get("type"), h["command"]])
print(json.dumps(out))
'''


def _git(*args: str, text=True):
    return subprocess.run(["git", "-C", str(REPO), *args], check=True, capture_output=True, text=text).stdout


def harvest(ref: str):
    found = {(plat, v): set() for plat in ("posix", "windows") for v in VARIANTS}
    failures = []
    shas = _git("log", "--format=%H", ref, "--", f"{SCRIPTS}/codex_install.py").split()
    for sha in shas:
        dest = WORK / sha[:12]
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
        blob = _git("archive", "--format=tar", sha, SCRIPTS, text=False)
        with tarfile.open(fileobj=io.BytesIO(blob)) as tar:
            tar.extractall(dest)
        scripts = dest / SCRIPTS
        for plat, key, table in (("linux", "posix", POSIX), ("win32", "windows", WINDOWS)):
            for variant, sent in table.items():
                r = subprocess.run([sys.executable, "-I", "-c", HARVEST, str(scripts), plat, json.dumps(sent)],
                                   capture_output=True, text=True, cwd=str(dest))
                if r.returncode:
                    failures.append((sha[:8], plat, variant, r.stderr.strip().splitlines()[-1:] or ["?"]))
                    continue
                found[(key, variant)].update(map(tuple, json.loads(r.stdout.strip().splitlines()[-1])))
        shutil.rmtree(dest)
    return found, failures, len(shas)


def versions() -> set:
    tags = _git("tag", "--merged", "HEAD").split()
    out = set()
    for tag in tags:
        name = tag[1:] if tag.startswith("v") else tag
        parts = name.split(".")
        if len(parts) == 3 and all(p.isdigit() for p in parts):
            out.add(name)
    return out


def existing():
    if not OUT.is_file():
        return {}, set()
    data = json.loads(OUT.read_text(encoding="utf-8"))
    # Entries only; a command-only template from before contexts proves nothing.
    templates = {tuple(k.split("/")): {tuple(t) for t in v if isinstance(t, list)}
                 for k, v in data["templates"].items()}
    return templates, set(data["versions"])


def render(templates, vers) -> str:
    data = {
        "_comment": "GENERATED by scripts/gen_shipped_codex_hook_templates.py by running every "
                    "committed codex_install.py with placeholder paths. Do not edit by hand. "
                    "codex_hook_provenance substitutes the real paths into each entry's command and "
                    "compares the whole entry (event, matcher, type, command) byte for byte.",
        "placeholders": {"posix": POSIX, "windows": WINDOWS},
        "templates": {f"{k[0]}/{k[1]}": [list(t) for t in sorted(v, key=repr)]
                      for k, v in sorted(templates.items())},
        "versions": sorted(vers, key=lambda x: tuple(int(p) for p in x.split("."))),
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ref", default="HEAD")
    args = ap.parse_args(argv)
    found, failures, n = harvest(args.ref)
    old_templates, old_vers = existing()
    templates = {k: found[k] | old_templates.get(k, set()) for k in found}
    vers = versions() | old_vers
    OUT.write_text(render(templates, vers), encoding="utf-8")
    sizes = ", ".join(f"{k[0]}/{k[1]} {len(v)}" for k, v in sorted(templates.items()))
    print(f"{n} codex_install.py versions; templates: {sizes}; {len(vers)} versions; "
          f"{len(failures)} harvest failures")
    for f in failures:
        print("  failed:", f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
