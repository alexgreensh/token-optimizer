#!/usr/bin/env python3
"""Regenerate skills/token-optimizer/scripts/shipped_hook_templates.py.

Collects every hook ``command`` string that any committed version of the
Claude Code hooks.json files has shipped (the files setup_all_hooks merges
into settings.json, plus their plugin/cowork mirror copies) and writes them as
one frozen set. The malformed-hook healer treats a settings.json command as
ours only when it is byte-identical to one of these, instantiated for the
running install root, or recorded in the provenance ledger.

Run after any hooks/hooks.json change (tests/test_hook_provenance.py fails
until the current commands are in the set):

    python3 scripts/gen_shipped_hook_templates.py [--ref HEAD]

Only ever adds: commands already in the generated file are kept even if the
history walk no longer finds them (a squashed or rewritten history must not
shrink what older installs can prove).
"""
from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "skills" / "token-optimizer" / "scripts" / "shipped_hook_templates.py"
SOURCES = (
    "hooks/hooks.json",
    "plugins/token-optimizer/hooks/hooks.json",
    "cowork/token-optimizer/hooks/hooks.json",
)

HEADER = '''"""Every hook command Token Optimizer has shipped in a Claude Code hooks.json.

GENERATED by scripts/gen_shipped_hook_templates.py from git history of:
{sources}
Do not edit by hand. Strings are exact (JSON-decoded) template bytes with the
literal ${{CLAUDE_PLUGIN_ROOT}} placeholder; hook_provenance instantiates them
for the running install root and compares byte for byte.
"""

SHIPPED_HOOK_TEMPLATES = frozenset((
'''


def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True,
                          capture_output=True, text=True).stdout


def collect(ref: str) -> set[str]:
    found: set[str] = set()
    for path in SOURCES:
        for sha in _git("log", "--format=%H", ref, "--", path).split():
            try:
                data = json.loads(_git("show", f"{sha}:{path}"))
            except (subprocess.CalledProcessError, ValueError):
                continue
            hooks = data.get("hooks") if isinstance(data, dict) else None
            for groups in (hooks or {}).values():
                for group in groups if isinstance(groups, list) else []:
                    for hook in (group.get("hooks") or []) if isinstance(group, dict) else []:
                        command = hook.get("command") if isinstance(hook, dict) else None
                        if isinstance(command, str) and command:
                            found.add(command)
    return found


def existing() -> set[str]:
    if not OUT.is_file():
        return set()
    tree = ast.parse(OUT.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "SHIPPED_HOOK_TEMPLATES":
            return set(ast.literal_eval(node.value.args[0]))
    return set()


def render(commands: set[str]) -> str:
    body = "".join(f"    {command!r},\n" for command in sorted(commands))
    return HEADER.format(sources="\n".join(f"  {s}" for s in SOURCES)) + body + "))\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default="HEAD")
    args = parser.parse_args(argv)
    commands = collect(args.ref) | existing()
    OUT.write_text(render(commands), encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(commands)} shipped hook commands")
    return 0


if __name__ == "__main__":
    sys.exit(main())
