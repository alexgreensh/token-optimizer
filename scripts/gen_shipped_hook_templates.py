#!/usr/bin/env python3
"""Regenerate skills/token-optimizer/scripts/shipped_hook_templates.py.

Collects every hook entry that any committed version of the Claude Code
hooks.json files has shipped (the files setup_all_hooks merges into
settings.json, plus their plugin/cowork mirror copies), each with the context
it shipped in: ``(event, matcher, hook type, command)``. The malformed-hook
healer treats a settings.json entry as ours only when that full context is
byte-identical to one of these (command instantiated for the running install
root), or recorded in the provenance ledger. An absent matcher is "", the
same rule setup_all_hooks uses to pick the group it writes into.

Run after any hooks/hooks.json change (tests/test_hook_provenance.py fails
until the current commands are in the set):

    python3 scripts/gen_shipped_hook_templates.py [--ref HEAD]

Only ever adds: contexts already in the generated file are kept even if the
history walk no longer finds them (a squashed or rewritten history must not
shrink what older installs can prove).
"""
from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "skills" / "token-optimizer" / "scripts" / "shipped_hook_templates.py"
SOURCES = (
    "hooks/hooks.json",
    "plugins/token-optimizer/hooks/hooks.json",
    "cowork/token-optimizer/hooks/hooks.json",
)

HEADER = '''"""Every hook command Token Optimizer has shipped in a Claude Code hooks.json.

GENERATED by scripts/gen_shipped_hook_templates.py from git history of:
{sources}
Do not edit by hand. Each entry is (event, matcher, hook type, command); the
command is the exact (JSON-decoded) template with the literal
${{CLAUDE_PLUGIN_ROOT}} placeholder. hook_provenance instantiates it for the
running install root and compares the whole tuple byte for byte.
"""

SHIPPED_HOOK_CONTEXTS = frozenset((
'''


def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True,
                          capture_output=True, text=True).stdout


def collect(ref: str) -> set:
    found: set = set()
    for path in SOURCES:
        for sha in _git("log", "--format=%H", ref, "--", path).split():
            try:
                data = json.loads(_git("show", f"{sha}:{path}"))
            except (subprocess.CalledProcessError, ValueError):
                continue
            hooks = data.get("hooks") if isinstance(data, dict) else None
            for event, groups in (hooks or {}).items():
                for group in groups if isinstance(groups, list) else []:
                    if not isinstance(group, dict):
                        continue
                    matcher = group.get("matcher", "")
                    if not isinstance(matcher, str):
                        continue
                    for hook in group.get("hooks") or []:
                        command = hook.get("command") if isinstance(hook, dict) else None
                        hook_type = hook.get("type") if isinstance(hook, dict) else None
                        if isinstance(command, str) and command and \
                                (hook_type is None or isinstance(hook_type, str)):
                            found.add((event, matcher, hook_type, command))
    return found


def existing() -> set:
    if not OUT.is_file():
        return set()
    tree = ast.parse(OUT.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "SHIPPED_HOOK_CONTEXTS":
            return set(ast.literal_eval(node.value.args[0]))
    return set()  # pre-context file: command-only entries carry no context to keep


def render(contexts: set) -> str:
    body = "".join(f"    {context!r},\n" for context in sorted(contexts, key=repr))
    return (HEADER.format(sources="\n".join(f"  {s}" for s in SOURCES)) + body + "))\n\n"
            "SHIPPED_HOOK_TEMPLATES = frozenset(context[3] for context in SHIPPED_HOOK_CONTEXTS)\n")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default="HEAD")
    args = parser.parse_args(argv)
    contexts = collect(args.ref) | existing()
    OUT.write_text(render(contexts), encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(contexts)} shipped hook contexts, "
          f"{len({c[3] for c in contexts})} commands")
    return 0


if __name__ == "__main__":
    sys.exit(main())
