def _make_package_lock(n_pkgs: int = 260) -> str:
    packages = {
        "": {
            "name": "acme-web-app",
            "version": "2.4.0",
            "dependencies": {"react": "^18.3.1", "zod": "^3.23.8"},
        }
    }
    for i in range(n_pkgs):
        pkg = f"node_modules/pkg-{i:04d}"
        packages[pkg] = {
            "version": f"1.{i % 20}.{i % 10}",
            "resolved": f"https://registry.npmjs.org/pkg-{i:04d}/-/pkg-{i:04d}-1.{i % 20}.{i % 10}.tgz",
            "integrity": f"sha512-{'A1b2C3d4E5f6' * 7}{i:04d}==",
            "license": "MIT",
            "engines": {"node": ">=18.0.0"},
        }
    return json.dumps(
        {"name": "acme-web-app", "version": "2.4.0", "lockfileVersion": 3, "requires": True, "packages": packages},
        indent=2,
    )


def _make_cargo_lock(n_pkgs: int = 240) -> str:
    blocks = ["# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n"]
    for i in range(n_pkgs):
        blocks.append(
            f'[[package]]\n'
            f'name = "crate-{i:04d}"\n'
            f'version = "0.{i % 30}.{i % 7}"\n'
            f'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            f'checksum = "{"a1b2c3d4" * 8}"\n'
            f'dependencies = [\n "serde",\n "tokio",\n]\n'
        )
    return "\n".join(blocks)


def _make_app_log(n_info: int = 650) -> str:
    lines = []
    for i in range(n_info):
        lines.append(
            f"2026-11-22T10:{(i // 60) % 60:02d}:{i % 60:02d}.123Z INFO  [worker-{i % 4}] "
            f"Processed job_id=job_{i:05d} latency_ms={12 + (i % 40)} status=200 ok"
        )
        if i == 120:
            lines.append("2026-11-22T10:02:00.500Z WARN  [pool] Connection pool saturation at 92% (184/200)")
        if i == 310:
            lines.append("2026-11-22T10:05:10.900Z ERROR [billing] PaymentChargeFailed: card_declined order_id=ord_99812")
            lines.append("Traceback (most recent call last):")
            lines.append('  File "/app/src/billing/charge.py", line 142, in execute_charge')
            lines.append("    raise PaymentChargeFailed('card_declined')")
        if i in (400, 401, 402):
            lines.append("2026-11-22T10:06:40.000Z WARN  [cache] Redis transient timeout on key=session:user_42")
        if i == 580:
            lines.append("2026-11-22T10:09:40.250Z FATAL [db] Deadlock detected on table=invoices tx_id=tx_7710")
    return "\n".join(lines) + "\n"


def _make_csv_dump(n_rows: int = 700) -> str:
    lines = ["event_id,timestamp,user_id,region,plan,amount_cents,status,latency_ms"]
    for i in range(n_rows):
        lines.append(
            f"evt_{i:06d},2026-11-22T12:{(i // 60) % 60:02d}:{i % 60:02d}Z,"
            f"usr_{i % 150:04d},us-east-1,pro,{2900 + (i % 5) * 100},settled,{45 + (i % 90)}"
        )
    return "\n".join(lines) + "\n"


def _make_jsonl_dump(n_rows: int = 380) -> str:
    lines = []
    for i in range(n_rows):
        rec = {
            "id": i,
            "ts": f"2026-11-22T11:{(i // 60) % 60:02d}:{i % 60:02d}Z",
            "service": "ingest-api",
            "level": "INFO",
            "bytes": 1024 + i,
            "path": f"/v2/items/{i:05d}/sync",
        }
        if i == 215:
            rec["level"] = "ERROR"
            rec["error"] = "upstream_502_bad_gateway"
        lines.append(json.dumps(rec))
    return "\n".join(lines) + "\n"


def _make_json_array_dump(n_items: int = 420) -> str:
    items = [
        {
            "sku": f"SKU-{i:05d}",
            "title": f"Widget Model {i}",
            "category": "hardware" if i % 2 == 0 else "accessories",
            "price_usd": round(9.99 + (i % 100), 2),
            "in_stock": i % 3 != 0,
            "warehouse": f"wh-{i % 5}",
        }
        for i in range(n_items)
    ]
    return json.dumps(items, indent=2)


def _make_minified_bundle(size_bytes: int = 60_000) -> str:
    chunk = "function _r(e,t){return e.map(function(n){return n*t+1})}var _x=_r([1,2,3],4);"
    repeats = (size_bytes // len(chunk)) + 2
    return "/*! acme-bundle v3.1.0 | MIT */" + (chunk * repeats)


def _make_source_map(n_sources: int = 120) -> str:
    sources = [f"webpack:///./src/components/Widget{i:03d}.tsx" for i in range(n_sources)]
    names = [f"sym_{i:04d}" for i in range(200)]
    mappings = ";".join("AAAA,CAAC,IAAI,GAAG,CAAC,GAAG,EAAE,CAAC" * 20 for _ in range(120))
    return json.dumps({"version": 3, "file": "app.min.js", "sources": sources, "names": names, "mappings": mappings})


def _make_sarif_report(n_notes: int = 160) -> str:
    results = []
    for i in range(n_notes):
        results.append({
            "ruleId": "INFO-STYLE-001",
            "level": "note",
            "message": {"text": f"Informational style note #{i} on generated fixture element"},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f"src/m{i:03d}.py"}, "region": {"startLine": i + 1}}}],
        })
    results.append({
        "ruleId": "SEC-SQLI-009",
        "level": "error",
        "message": {"text": "Unsanitized user input flows into raw SQL query"},
        "locations": [{"physicalLocation": {"artifactLocation": {"uri": "src/db/query.py"}, "region": {"startLine": 88}}}],
    })
    return json.dumps({"version": "2.1.0", "runs": [{"tool": {"driver": {"name": "secscan"}}, "results": results}]}, indent=2)


